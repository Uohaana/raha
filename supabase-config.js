async function rahaFetchProducts() {
  const db = window.RAHA_SUPABASE_CLIENT;
  if (!db || window.RAHA_SUPABASE_URL.includes("YOUR_PROJECT"))
    return window.RAHA_PRODUCTS;
  const { data, error } = await db
    .from("perfumes")
    .select("*")
    .eq("status", "published")
    .order("created_at", { ascending: true })
    .limit(100);
  return error || !data?.length ? window.RAHA_PRODUCTS : data;
}
